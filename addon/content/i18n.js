	let lang = "pt-PT";

	/** "auto" segue a língua do Zotero: português fica PT-PT, tudo o resto inglês. */
	function resolve(pref, zoteroLocale) {
		if (pref === "pt-PT" || pref === "en") return pref;
		return /^pt/i.test(String(zoteroLocale || "")) ? "pt-PT" : "en";
	}

	function setLang(l) {
		lang = STR[l] ? l : "pt-PT";
		return lang;
	}

	function getLang() {
		return lang;
	}

	function t(key, vars) {
		let s = STR[lang][key];
		if (s == null) s = STR["pt-PT"][key];
		if (s == null) return key;
		if (vars) s = s.replace(/\{(\w+)\}/g, (all, k) => (vars[k] != null ? String(vars[k]) : all));
		return s;
	}

	function has(key) {
		return STR[lang][key] != null || STR["pt-PT"][key] != null;
	}

	return { STR, t, has, setLang, getLang, resolve };
